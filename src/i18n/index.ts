export const languageSetting = computed(() => setting.value);
export const locale = computed(() => resolved.value);

function resolveLocale(value: LanguageSetting): ResolvedLocale {
  if (value === 'zh-CN' || value === 'en') {
    return value;
  }
  const browser = typeof navigator !== 'undefined' ? navigator.language.toLowerCase() : 'zh';
  return browser.startsWith('zh') ? 'zh-CN' : 'en';
}

export function t(key: string, vars: Record<string, string | number> = {}): string {
  let text = messages[resolved.value][key] ?? messages['zh-CN'][key] ?? key;
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

export async function initLanguage(): Promise<void> {
  if (typeof chrome !== 'undefined' && chrome.storage?.local) {
    try {
      const result = await chrome.storage.local.get(STORAGE_KEY);
      const stored = result[STORAGE_KEY];
      if (stored === 'auto' || stored === 'zh-CN' || stored === 'en') {
        setting.value = stored;
      }
    } catch {
      // 使用默认设置
    }
  }
  resolved.value = resolveLocale(setting.value);
}

export async function setLanguage(next: LanguageSetting): Promise<void> {
  setting.value = next;
  resolved.value = resolveLocale(next);
  if (typeof chrome !== 'undefined' && chrome.storage?.local) {
    try {
      await chrome.storage.local.set({ [STORAGE_KEY]: next });
    } catch {
      // 不阻断界面切换
    }
  }
}

export function useI18n() {
  return {
    language: languageSetting,
    locale,
    t,
    setLanguage,
  };
}

